# Only reference environment
# The dataset was generated by running the following python code from
# the root of the directory (where this file is contained):
#   >>> import src.light_tunnel as light_tunnel
#   >>> light_tunnel.prepare_experiments_directory('light_tunnel_experiments/', [1000], ['ref'], 100, 'ref')
